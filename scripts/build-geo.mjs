// Builds the self-hosted cartography used by the map and the editorial visuals.
// Usage: node scripts/build-geo.mjs <dir-with-sources>
// Sources (open data):
//   regions.geojson, provinces.geojson — openpolis/geojson-italy (CC BY 4.0, ISTAT)
//   countries.geojson                 — Natural Earth 1:50m admin 0 (public domain)
import mapshaper from 'mapshaper';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';

const src = process.argv[2];
if (!src) throw new Error('Usage: node scripts/build-geo.mjs <source-dir>');
const root = new URL('..', import.meta.url);
const publicGeo = new URL('public/geo/', root);
const generated = new URL('src/lib/geo/', root);
await mkdir(publicGeo, { recursive: true });
await mkdir(generated, { recursive: true });

async function simplify(file, cmds) {
  const input = await readFile(path.join(src, file), 'utf8');
  const out = await mapshaper.applyCommands(`-i in.json ${cmds} -o out.json format=geojson precision=0.001`, { 'in.json': input });
  return JSON.parse(out['out.json'].toString());
}

const slugify = (s) =>
  s
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/['’]/g, '-')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');

// Canonical display names (IT/EN). Keys are openpolis reg_name values.
const REGION_NAMES = {
  Piemonte: ['Piemonte', 'Piedmont'],
  "Valle d'Aosta/Vallée d'Aoste": ["Valle d'Aosta", 'Aosta Valley'],
  Liguria: ['Liguria', 'Liguria'],
  Lombardia: ['Lombardia', 'Lombardy'],
  'Trentino-Alto Adige/Südtirol': ['Trentino-Alto Adige', 'Trentino-South Tyrol'],
  Veneto: ['Veneto', 'Veneto'],
  'Friuli-Venezia Giulia': ['Friuli-Venezia Giulia', 'Friuli-Venezia Giulia'],
  'Emilia-Romagna': ['Emilia-Romagna', 'Emilia-Romagna'],
  Marche: ['Marche', 'Marche'],
  Toscana: ['Toscana', 'Tuscany'],
  Umbria: ['Umbria', 'Umbria'],
  Lazio: ['Lazio', 'Lazio'],
  Campania: ['Campania', 'Campania'],
  Abruzzo: ['Abruzzo', 'Abruzzo'],
  Molise: ['Molise', 'Molise'],
  Puglia: ['Puglia', 'Apulia'],
  Basilicata: ['Basilicata', 'Basilicata'],
  Calabria: ['Calabria', 'Calabria'],
  Sicilia: ['Sicilia', 'Sicily'],
  Sardegna: ['Sardegna', 'Sardinia'],
};

function bbox(geom) {
  let minX = Infinity,
    minY = Infinity,
    maxX = -Infinity,
    maxY = -Infinity;
  const walk = (c) => {
    if (typeof c[0] === 'number') {
      minX = Math.min(minX, c[0]);
      maxX = Math.max(maxX, c[0]);
      minY = Math.min(minY, c[1]);
      maxY = Math.max(maxY, c[1]);
    } else c.forEach(walk);
  };
  walk(geom.coordinates);
  return [minX, minY, maxX, maxY].map((n) => Math.round(n * 1000) / 1000);
}

const regions = await simplify('regions.geojson', '-simplify 6% keep-shapes -filter-islands min-area=4km2');
const provinces = await simplify('provinces.geojson', '-simplify 5% keep-shapes -filter-islands min-area=4km2');
const europe = await simplify(
  'countries.geojson',
  '-clip bbox=-14,30,36,62 -simplify 25% keep-shapes -filter-fields NAME,ISO_A2 -filter \'ISO_A2 !== "IT"\'',
);

const regionMeta = regions.features.map((f) => {
  const [it, en] = REGION_NAMES[f.properties.reg_name] ?? [f.properties.reg_name, f.properties.reg_name];
  const slug = slugify(it);
  f.properties = { slug, name: it };
  return { slug, it, en, iso: '', bbox: bbox(f.geometry) };
});
const regionSlugByOpenpolis = Object.fromEntries(Object.entries(REGION_NAMES).map(([k, [it]]) => [k, slugify(it)]));
const provinceMeta = provinces.features.map((f) => {
  const p = f.properties;
  const name = p.prov_name.split('/')[0];
  const slug = slugify(name);
  const region = regionSlugByOpenpolis[p.reg_name];
  f.properties = { slug, region, name };
  return { slug, name, code: p.prov_acr, region, bbox: bbox(f.geometry) };
});
provinceMeta.sort((a, b) => a.name.localeCompare(b.name, 'it'));
regionMeta.sort((a, b) => a.it.localeCompare(b.it, 'it'));

await writeFile(new URL('italy-regions.json', publicGeo), JSON.stringify(regions));
await writeFile(new URL('italy-provinces.json', publicGeo), JSON.stringify(provinces));
await writeFile(new URL('europe.json', publicGeo), JSON.stringify(europe));
// Kept outside public/: only used at build time by scripts/build-visuals.mjs.
await writeFile(new URL('data/geo/italy-regions.json', root), JSON.stringify(regions)).catch(async () => {
  await mkdir(new URL('data/geo/', root), { recursive: true });
  await writeFile(new URL('data/geo/italy-regions.json', root), JSON.stringify(regions));
});

const ts = `// AUTO-GENERATED by scripts/build-geo.mjs — do not edit by hand.
// Source: openpolis/geojson-italy (ISTAT boundaries, CC BY 4.0).

export type RegionMeta = { slug: string; it: string; en: string; bbox: [number, number, number, number] };
export type ProvinceMeta = { slug: string; name: string; code: string; region: string; bbox: [number, number, number, number] };

export const REGIONS: RegionMeta[] = ${JSON.stringify(
  regionMeta.map(({ iso, ...r }) => r),
  null,
  0,
)};

export const PROVINCES: ProvinceMeta[] = ${JSON.stringify(provinceMeta, null, 0)};

export const ITALY_BBOX: [number, number, number, number] = [6.6, 35.5, 18.6, 47.1];
`;
await writeFile(new URL('territories.ts', generated), ts);
console.log(`regions ${regionMeta.length}, provinces ${provinceMeta.length}, europe ${europe.features.length}`);
