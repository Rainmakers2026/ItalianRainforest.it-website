// Brand assets from the official Italian Rainforest logos supplied by Rainmakers.
//   node scripts/prepare-brand.mjs <dir with 1.webp (white logo) and 2.webp (blue logo)>
// Outputs: public/brand/irf-logo-{white,blue}.{webp,png}, public/brand/irf-mark-{white,blue}.png
// and the favicon set (src/app/icon.png, src/app/apple-icon.png) from the blue circle mark.
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = process.argv[2];
if (!src) throw new Error('Usage: node scripts/prepare-brand.mjs <source-dir>');
const out = (p) => path.join(root, p);

/** x where the circle mark ends: first fully transparent column after it. */
async function markEnd(buf) {
  const { data, info } = await sharp(buf).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  let seen = false;
  for (let x = 0; x < info.width; x++) {
    let any = false;
    for (let y = 0; y < info.height; y += 2) if (data[(y * info.width + x) * 4 + 3] > 30) { any = true; break; }
    if (any) seen = true;
    else if (seen) return { x, ...info };
  }
  return { x: info.height, ...info };
}

for (const [file, tone] of [['1.webp', 'white'], ['2.webp', 'blue']]) {
  const buf = await readFile(path.join(src, file));
  const lockup = await sharp(buf).trim().toBuffer();
  await sharp(lockup).resize({ height: 240 }).webp({ quality: 95, alphaQuality: 100 }).toFile(out(`public/brand/irf-logo-${tone}.webp`));
  await sharp(lockup).resize({ height: 240 }).png({ compressionLevel: 9 }).toFile(out(`public/brand/irf-logo-${tone}.png`));
  const { x, height } = await markEnd(lockup);
  const mark = await sharp(lockup).extract({ left: 0, top: 0, width: x, height }).trim().toBuffer();
  await sharp(mark).resize({ width: 512, height: 512, fit: 'contain', background: { r: 0, g: 0, b: 0, alpha: 0 } }).png().toFile(out(`public/brand/irf-mark-${tone}.png`));
  if (tone === 'blue') {
    // Favicon: the circle mark, strokes thickened so it reads at 16–32 px, white inside the ring.
    const S = 512;
    const markPx = await sharp(mark).resize({ width: S - 24, height: S - 24, fit: 'contain', background: { r: 0, g: 0, b: 0, alpha: 0 } })
      .extend({ top: 12, bottom: 12, left: 12, right: 12, background: { r: 0, g: 0, b: 0, alpha: 0 } })
      .ensureAlpha().raw().toBuffer();
    const alpha = Buffer.alloc(S * S);
    for (let i = 0; i < S * S; i++) alpha[i] = markPx[i * 4 + 3];
        // Disc-shaped max filter (radius R px): every stroke grows by R on each side.
    const R = 6;
    const offs = [];
    for (let dy = -R; dy <= R; dy++) for (let dx = -R; dx <= R; dx++) if (dx * dx + dy * dy <= R * R) offs.push([dx, dy]);
    const grown = Buffer.alloc(S * S);
    for (let y = 0; y < S; y++)
      for (let x = 0; x < S; x++) {
        let m = 0;
        for (const [dx, dy] of offs) {
          const xx = x + dx, yy = y + dy;
          if (xx < 0 || yy < 0 || xx >= S || yy >= S) continue;
          const v = alpha[yy * S + xx];
          if (v > m) { m = v; if (m === 255) break; }
        }
        grown[y * S + x] = m;
      }
    const thick = Buffer.alloc(S * S * 4);
    for (let i = 0; i < S * S; i++) {
      thick[i * 4] = 0x45; thick[i * 4 + 1] = 0x5f; thick[i * 4 + 2] = 0xd6; // IRF blue
      thick[i * 4 + 3] = Math.max(grown[i], alpha[i]);
    }
    const thickPng = await sharp(thick, { raw: { width: S, height: S, channels: 4 } }).png().toBuffer();
    const disc = Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="${S}" height="${S}"><circle cx="${S / 2}" cy="${S / 2}" r="${S / 2 - 20}" fill="#ffffff"/></svg>`);
    const icon = await sharp(disc).composite([{ input: thickPng }]).png().toBuffer();
    await sharp(icon).toFile(out('src/app/icon.png'));
    await sharp(icon).resize(48).png().toFile(out('public/brand/favicon-48.png'));
    // iOS ignores transparency: white tile with breathing room.
    await sharp(icon).resize(156).extend({ top: 12, bottom: 12, left: 12, right: 12, background: '#ffffff' }).flatten({ background: '#ffffff' })
      .png().toFile(out('src/app/apple-icon.png'));
  }
  const m = await sharp(out(`public/brand/irf-logo-${tone}.png`)).metadata();
  console.log(tone, 'lockup', m.width, 'x', m.height, 'mark end at', x);
}
await writeFile(out('public/brand/README.md'), 'Official Italian Rainforest logos. Generated by scripts/prepare-brand.mjs — white for dark/coloured backgrounds, blue for white backgrounds and the footer.\n');
