// Imports the IRF database export (CSV, same columns as the Airtable base "Rainmakers OS")
// into data/snapshot/irf-records.json and prepares the player logos.
//
//   node scripts/import-irf-csv.mjs [csv] [logo-dir]
//     csv       default data/source/irf-database.csv
//     logo-dir  folder with one sub-folder per PLAYER TYPE containing "<Company name>.webp"
//               (e.g. the unzipped "LOGHI PLAYER" archive). Optional: without it the
//               existing logo manifest is kept.
//
// What it does (all deterministic, nothing invented):
//   - drops template rows ("Nome", "Nome azienda") and STARTUP-only rows;
//   - keeps the first occurrence of each company name (the export repeats a block);
//   - "DA VERIFICARE", "Not Answered", empty → null; cookie/404 boilerplate descriptions → null;
//   - checks the address against the REGION column: an address whose province belongs
//     to another region is kept for reference but not used for the map position;
//   - logos: matched to players by normalised company name, trimmed, resized to max 640 px,
//     stored content-addressed in public/logos/players/<hash>.webp (identical images
//     shared by sibling organisations are stored once). Logos with no matching player
//     are archived (not published) in data/logos/unmatched/<type>/.
//   - writes docs/data-quality.md with everything that needs a human check.
import { createHash } from 'node:crypto';
import { existsSync } from 'node:fs';
import { copyFile, mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { logoHash, processLogo } from './lib/logo-image.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const csvPath = path.resolve(process.argv[2] ?? path.join(root, 'data/source/irf-database.csv'));
const logoDir = process.argv[3] ? path.resolve(process.argv[3]) : null;

// ---------- CSV ----------
function parseCsv(t) {
  const rows = [];
  let row = [], f = '', q = false;
  for (let i = 0; i < t.length; i++) {
    const c = t[i];
    if (q) {
      if (c === '"') { if (t[i + 1] === '"') { f += '"'; i++; } else q = false; } else f += c;
    } else if (c === '"') q = true;
    else if (c === ',') { row.push(f); f = ''; }
    else if (c === '\n' || c === '\r') { if (c === '\r' && t[i + 1] === '\n') i++; row.push(f); rows.push(row); row = []; f = ''; }
    else f += c;
  }
  if (f || row.length) { row.push(f); rows.push(row); }
  return rows;
}

const PLACEHOLDER = /^(da verificare|not answered|n\/?a|-|–|nome|sede|regione|tbd)$/i;
const clean = (v) => {
  const s = (v ?? '').replace(/\s+/g, ' ').trim();
  return !s || PLACEHOLDER.test(s) ? null : s;
};
export const normName = (s) =>
  s.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase().replace(/&/g, 'and').replace(/[^a-z0-9]+/g, '');
const slugify = (s) =>
  s.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase().replace(/['’]/g, '-').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

// Boilerplate captured by the scraper instead of a real description.
const JUNK_DESCRIPTION = [
  /\buses? cookies\b/i,
  /\bcookies? (or|and) similar technologies\b/i,
  /unable to find the requested page/i,
  /requested page/i,
  /page (not found|has been moved)/i,
];

// ---------- territories (generated by build-geo) ----------
const terr = await readFile(path.join(root, 'src/lib/geo/territories.ts'), 'utf8');
const REGIONS = JSON.parse(terr.match(/export const REGIONS: RegionMeta\[\] = (\[.*?\]);/s)[1]);
const PROVINCES = JSON.parse(terr.match(/export const PROVINCES: ProvinceMeta\[\] = (\[.*?\]);/s)[1]);
const regionByName = new Map(REGIONS.flatMap((r) => [[slugify(r.it), r], [slugify(r.en), r], [r.slug, r]]));
regionByName.set('trentino-alto-adige-sudtirol', regionByName.get('trentino-alto-adige'));
regionByName.set('piamonte', regionByName.get('piemonte'));
const provByCode = new Map(PROVINCES.map((p) => [p.code, p]));
provByCode.set('SU', PROVINCES.find((p) => p.slug === 'sulcis-iglesiente')); // Sud Sardegna (2016+)

const CITY_ALIASES = {
  turin: 'Torino', rome: 'Roma', milan: 'Milano', genoa: 'Genova', florence: 'Firenze', naples: 'Napoli',
  venice: 'Venezia', vi: 'Vicenza', ca: 'Cagliari', ct: 'Catania', reggio: "Reggio nell'Emilia",
  'reggio-nell-emilia': "Reggio nell'Emilia", ascoli: 'Ascoli Piceno', pesaro: 'Pesaro', forli: 'Forlì',
  monza: 'Monza', peschiera: 'Peschiera Borromeo',
};
const titleCase = (s) => s.toLowerCase().replace(/(^|[\s'-])(\p{L})/gu, (m, a, b) => a + b.toUpperCase());
function cleanCity(raw) {
  const s = clean(raw?.replace(/^[–-]\s*/, ''));
  if (!s) return null;
  if (/hoofdstedelijk|gewest|piamonte/i.test(s)) return null; // region names or foreign admin units
  return CITY_ALIASES[slugify(s)] ?? titleCase(s);
}

/** "Via X, 20123 Milano MI, Italy" → { city: 'Milano', province } */
function parseAddress(addr) {
  if (!addr) return null;
  const m = addr.match(/\b(\d{5})\s+([^,\d]+?)\s+([A-Z]{2})\b/);
  if (!m) return { cap: null, city: null, province: null };
  const province = provByCode.get(m[3]) ?? null;
  return { cap: m[1], city: m[2].trim(), province };
}

// ---------- read + clean ----------
const rows = parseCsv((await readFile(csvPath, 'utf8')).replace(/^﻿/, ''));
const header = rows.shift().map((h) => h.trim());
const col = (name) => {
  const i = header.findIndex((h) => h.toUpperCase().startsWith(name));
  if (i < 0) throw new Error(`Column "${name}" not found in ${csvPath}`);
  return i;
};
const C = {
  name: header[0] === 'Map' ? 0 : col('COMPANY NAME'),
  website: col('WEBSITE'),
  description: col('SHORT DESCRIPTION'),
  type: col('PLAYER TYPE'),
  address: col('ADDRESS'),
  region: col('REGION'),
  city: col('CITY'),
  industry: col('INDUSTRY'),
  status: col('STATUS'),
  logo: col('LOGO'),
};

const report = { template: [], duplicateRows: [], startupOnly: [], junkDescription: [], addressMismatch: [], noRegion: [], logoMissing: [], logoNoFlag: [], sharedLogos: [], unmatchedLogos: [] };
const seen = new Map();
for (const r of rows) {
  const name = clean(r[C.name]);
  if (!name) continue;
  if (/^nome( azienda)?$/i.test(name)) { report.template.push(name); continue; }
  const key = normName(name);
  if (seen.has(key)) { report.duplicateRows.push(name); continue; }
  seen.set(key, r);
}

const records = [];
for (const [key, r] of seen) {
  const name = clean(r[C.name]);
  const types = [...new Set((r[C.type] ?? '').split(';').map((s) => clean(s)).filter(Boolean).map((s) => s.toUpperCase()))];
  const enablerTypes = types.filter((t) => t !== 'STARTUP');
  if (types.length && !enablerTypes.length) { report.startupOnly.push(name); continue; }

  let description = clean(r[C.description]);
  if (description && JUNK_DESCRIPTION.some((re) => re.test(description))) { report.junkDescription.push(name); description = null; }

  const regionRaw = clean(r[C.region]);
  const regionMeta = regionRaw ? regionByName.get(slugify(regionRaw)) ?? null : null;
  const address = clean(r[C.address]);
  const parsed = parseAddress(address);
  const addrRegion = parsed?.province?.region ?? null;
  // The address is trusted for the map only when it agrees with REGION (or REGION is empty).
  const addressConsistent = !!addrRegion && (!regionMeta || regionMeta.slug === addrRegion);
  if (address && addrRegion && regionMeta && !addressConsistent)
    report.addressMismatch.push(`${name}: REGION=${regionMeta.it}, address="${address}"`);
  const region = regionMeta ?? (addressConsistent ? REGIONS.find((x) => x.slug === addrRegion) : null);
  const cityFromCol = cleanCity(r[C.city]);
  const city = (addressConsistent ? cleanCity(parsed.city) : null) ?? cityFromCol;
  const province = addressConsistent ? parsed.province : null;
  if (!region) report.noRegion.push(name);

  const industries = [...new Set((r[C.industry] ?? '').split(/[;,]/).map((s) => clean(s)).filter((s) => s && !/^it$/i.test(s)))];
  const statusRaw = clean(r[C.status])?.toUpperCase() ?? null;

  records.push({
    id: `irf_${createHash('sha256').update(key).digest('hex').slice(0, 14)}`,
    fields: {
      'COMPANY NAME': name,
      WEBSITE: clean(r[C.website]),
      'SHORT DESCRIPTION': description,
      'PLAYER TYPE': enablerTypes,
      ADDRESS: address,
      'ADDRESS CHECK': address ? (addressConsistent ? 'ok' : addrRegion ? 'region-mismatch' : 'unparsed') : null,
      REGION: region?.it ?? null,
      PROVINCE: province?.code ?? null,
      CITY: city,
      INDUSTRY: industries,
      STATUS: statusRaw === 'ACTIVE' ? 'ACTIVE' : statusRaw === 'INACTIVE' ? 'INACTIVE' : 'DA VERIFICARE',
      'LOGO FLAG': clean(r[C.logo])?.toUpperCase() ?? null,
    },
    _key: key,
  });
}

// ---------- logos ----------
const manifestPath = path.join(root, 'data/snapshot/logos.json');
let logos = existsSync(manifestPath) ? JSON.parse(await readFile(manifestPath, 'utf8')).logos : {};
if (logoDir) {
  logos = {};
  const outDir = path.join(root, 'public/logos/players');
  const archiveDir = path.join(root, 'data/logos/unmatched');
  await rm(outDir, { recursive: true, force: true });
  await rm(archiveDir, { recursive: true, force: true });
  await mkdir(outDir, { recursive: true });
  const byKey = new Map(records.map((r) => [r._key, r]));
  const byHash = new Map();
  for (const folder of (await readdir(logoDir, { withFileTypes: true })).filter((d) => d.isDirectory())) {
    for (const file of await readdir(path.join(logoDir, folder.name))) {
      if (!/\.(webp|png|jpe?g|svg)$/i.test(file)) continue;
      const src = path.join(logoDir, folder.name, file);
      const key = normName(file.replace(/\.[^.]+$/, ''));
      const rec = byKey.get(key);
      if (!rec) {
        // Not a player of the database (e.g. startups): archived, never published.
        await mkdir(path.join(archiveDir, folder.name), { recursive: true });
        await copyFile(src, path.join(archiveDir, folder.name, file));
        report.unmatchedLogos.push(`${folder.name}/${file}`);
        continue;
      }
      if (logos[rec.id]) continue; // same company listed under several types
      const buf = await readFile(src);
      const hash = logoHash(buf);
      if (!byHash.has(hash)) byHash.set(hash, { ...(await processLogo(buf, outDir, hash)), names: [] });
      const entry = byHash.get(hash);
      entry.names.push(rec.fields['COMPANY NAME']);
      logos[rec.id] = { src: entry.src, onLight: entry.onLight, w: entry.w, h: entry.h, tone: entry.tone };
    }
  }
  for (const e of byHash.values()) if (e.names.length > 1) report.sharedLogos.push(e.names.join(' = '));
  await writeFile(manifestPath, JSON.stringify({ _about: 'Player logos, keyed by record id. Generated by scripts/import-irf-csv.mjs.', logos }, null, 1));
}
// Logos scraped from the players' websites (scripts/scrape-logos.mjs) fill the gaps only.
const scrapedPath = path.join(root, 'data/snapshot/logos-scraped.json');
const scraped = existsSync(scrapedPath) ? JSON.parse(await readFile(scrapedPath, 'utf8')).logos : {};
for (const [id, l] of Object.entries(scraped)) if (!logos[id]) logos[id] = l;
for (const r of records) {
  if (logos[r.id]) r.fields.LOGO = logos[r.id];
  else if (r.fields['LOGO FLAG'] === 'SI') report.logoMissing.push(r.fields['COMPANY NAME']);
  if (logos[r.id] && r.fields['LOGO FLAG'] !== 'SI') report.logoNoFlag.push(r.fields['COMPANY NAME']);
}

// ---------- geocoding cache (filled by scripts/geocode-irf.mjs) ----------
const geoPath = path.join(root, 'data/snapshot/geocode-cache.json');
const geo = existsSync(geoPath) ? JSON.parse(await readFile(geoPath, 'utf8')) : {};
for (const r of records) {
  const g = geo[r.id];
  if (g && g.lat != null) {
    r.fields.Latitude = g.lat;
    r.fields.Longitude = g.lng;
    r.fields['GEO PRECISION'] = g.precision;
  }
}

const out = {
  source: path.basename(csvPath),
  importedAt: new Date().toISOString(),
  // Date of the database export (owner-provided). Shown on the site as "updated on".
  exportDate: process.env.IRF_EXPORT_DATE ?? '2026-11-17',
  records: records.map(({ _key, ...r }) => r),
};
await writeFile(path.join(root, 'data/snapshot/irf-records.json'), JSON.stringify(out, null, 1));

// ---------- report ----------
const list = (a) => (a.length ? a.map((s) => `- ${s}`).join('\n') : '_none_');
const md = `# Data quality — IRF database import

Generated by \`scripts/import-irf-csv.mjs\` on ${out.importedAt.slice(0, 10)} from \`${out.source}\`.
Nothing below was changed by hand: these are the rows that need a check in the source (Airtable "Rainmakers OS").

| | |
|---|---|
| Rows in the export | ${rows.length} |
| Unique organisations imported | ${records.length} |
| Repeated rows skipped (same name) | ${report.duplicateRows.length} |
| Template rows skipped | ${report.template.length} |
| Organisations with a logo | ${Object.keys(logos).length} |
| Organisations located on the map | ${records.filter((r) => r.fields.Latitude != null).length} |

## Addresses that contradict the REGION column (${report.addressMismatch.length})
The map uses REGION/CITY for these, not the address.
${list(report.addressMismatch)}

## Organisations without a region (${report.noRegion.length})
They are listed in the database but cannot be placed on the map.
${list(report.noRegion)}

## Descriptions replaced by an empty value (${report.junkDescription.length})
The scraped text was a cookie banner or an error page.
${list(report.junkDescription)}

## LOGO = SI but no logo file (${report.logoMissing.length})
${list(report.logoMissing)}

## Same logo image used by different records (${report.sharedLogos.length})
Some are sibling organisations, others are probably the same organisation entered twice — worth merging in the source.
${list(report.sharedLogos)}

## Logo files without a matching organisation (${report.unmatchedLogos.length})
Archived in \`data/logos/unmatched/\`, not published.
${list(report.unmatchedLogos)}

## Repeated rows skipped (${report.duplicateRows.length})
${list(report.duplicateRows)}
`;
await writeFile(path.join(root, 'docs/data-quality.md'), md);
console.log(`Imported ${records.length} organisations, ${Object.keys(logos).length} logos, ${report.addressMismatch.length} address mismatches, ${report.noRegion.length} without region.`);
