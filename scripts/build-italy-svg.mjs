// Builds src/lib/geo/italy-svg.ts: simplified SVG paths of the Italian regions
// (and of Lombardy's provinces) for the "Una mappa viva" infographic, plus a few
// deterministic points inside Lombardy where the umbrella markers are drawn.
// Source: public/geo/*.json (ISTAT boundaries via openpolis, CC BY 4.0).
// Usage: node scripts/build-italy-svg.mjs
import { readFile, writeFile } from 'node:fs/promises';

const root = new URL('..', import.meta.url);
const regions = JSON.parse(await readFile(new URL('public/geo/italy-regions.json', root), 'utf8'));
const provinces = JSON.parse(await readFile(new URL('public/geo/italy-provinces.json', root), 'utf8'));

const FOCUS = 'lombardia';
const [minLng, maxLat] = [6.55, 47.15];
const K = 46; // px per degree of latitude
const COS = Math.cos((42 * Math.PI) / 180);
const project = ([lng, lat]) => [(lng - minLng) * COS * K, (maxLat - lat) * K];

const polygonsOf = (g) => (g.type === 'Polygon' ? [g.coordinates] : g.coordinates);

function ringPath(ring) {
  const pts = [];
  for (const c of ring) {
    const p = project(c);
    const last = pts[pts.length - 1];
    if (!last || Math.hypot(p[0] - last[0], p[1] - last[1]) > 1.6) pts.push(p);
  }
  if (pts.length < 3) return '';
  return `M${pts.map((p) => `${p[0].toFixed(1)} ${p[1].toFixed(1)}`).join('L')}Z`;
}
const pathOf = (g) =>
  polygonsOf(g)
    .flatMap((poly) => poly.map(ringPath))
    .filter(Boolean)
    .join('');

let maxX = 0;
let maxY = 0;
for (const f of regions.features)
  for (const poly of polygonsOf(f.geometry))
    for (const [x, y] of poly[0].map(project)) {
      maxX = Math.max(maxX, x);
      maxY = Math.max(maxY, y);
    }

const regionPaths = regions.features.map((f) => ({ slug: f.properties.slug, d: pathOf(f.geometry) }));
const focus = regions.features.find((f) => f.properties.slug === FOCUS);
const focusProvinces = provinces.features
  .filter((f) => f.properties.region === FOCUS)
  .map((f) => pathOf(f.geometry));

// Point-in-polygon (even-odd) on the projected outer rings of the focus region.
const rings = polygonsOf(focus.geometry).map((poly) => poly[0].map(project));
const inside = ([x, y]) =>
  rings.some((r) => {
    let c = false;
    for (let i = 0, j = r.length - 1; i < r.length; j = i++) {
      const [xi, yi] = r[i];
      const [xj, yj] = r[j];
      if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) c = !c;
    }
    return c;
  });
const xs = rings.flat().map((p) => p[0]);
const ys = rings.flat().map((p) => p[1]);
const box = [Math.min(...xs), Math.min(...ys), Math.max(...xs), Math.max(...ys)];
const markers = [];
const STEP = 15;
for (let y = box[1] + STEP / 2; y < box[3]; y += STEP)
  for (let x = box[0] + STEP / 2 + ((y / STEP) % 2) * (STEP / 2); x < box[2]; x += STEP)
    if (inside([x, y]) && inside([x + 4, y]) && inside([x - 4, y])) markers.push([+x.toFixed(1), +y.toFixed(1)]);
// Keep a readable number of markers, evenly spread.
const keep = markers.filter((_, i) => i % Math.max(1, Math.round(markers.length / 16)) === 0);
const centroid = [(box[0] + box[2]) / 2, (box[1] + box[3]) / 2].map((v) => +v.toFixed(1));

const out = `// AUTO-GENERATED by scripts/build-italy-svg.mjs — do not edit by hand.
// Source: openpolis/geojson-italy (ISTAT boundaries, CC BY 4.0).

export const ITALY_VIEWBOX = '0 0 ${Math.ceil(maxX)} ${Math.ceil(maxY)}';
export const ITALY_REGIONS: { slug: string; d: string }[] = ${JSON.stringify(regionPaths)};
export const FOCUS_REGION = '${FOCUS}';
export const FOCUS_PROVINCES: string[] = ${JSON.stringify(focusProvinces)};
export const FOCUS_BOX: [number, number, number, number] = ${JSON.stringify(box.map((v) => +v.toFixed(1)))};
export const FOCUS_CENTROID: [number, number] = ${JSON.stringify(centroid)};
export const FOCUS_MARKERS: [number, number][] = ${JSON.stringify(keep)};
`;
await writeFile(new URL('src/lib/geo/italy-svg.ts', root), out);
console.log(`✔ italy-svg.ts: ${regionPaths.length} regions, ${focusProvinces.length} focus provinces, ${keep.length} markers, ${(out.length / 1024).toFixed(1)} KB`);
