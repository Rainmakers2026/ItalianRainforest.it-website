-- =============================================================================
-- Italian Rainforest — 03 · download_registrations (new)
-- Downloads (CSV, Excel, map PNG / PDF, complete database):
--   entry_type REGISTRATION = the one-time sign-up before the first download
--                             (POST /api/signup with a download reason)
--   entry_type EVENT        = every download by a signed-up visitor
--                             (POST /api/download for CSV / Excel / map PDF list;
--                              POST /api/signup with entry "event" for the map PNG,
--                              which is drawn in the browser)
--
-- Run once in Supabase → SQL Editor (project qwdajoztlpisrzieziup).
-- =============================================================================
begin;

create table public.download_registrations (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now(),
  -- idempotency key generated by the browser for each action (retries do not duplicate)
  request_id uuid not null,
  entry_type text not null,
  -- for EVENT rows: request_id of the visitor's sign-up (it may live in sharing_is_caring_registrations)
  registration_id uuid,
  source text not null default 'ITALIAN RAINFOREST WEBSITE',
  first_name text not null,
  last_name text not null,
  email text not null,
  -- what was requested: DOWNLOAD_CSV, DOWNLOAD_XLSX, DOWNLOAD_BULK, MAP_CSV, MAP_PNG, MAP_PDF
  request_type text not null,
  -- EVENT rows: file actually produced, scope, active filters (public filter query), rows
  file_format text,
  download_scope text,
  filter_query text,
  row_count integer,
  -- provenance: real page language, page, section, CTA, UTM
  locale text not null,
  page_path text not null,
  page_section text not null,
  cta text not null,
  utm jsonb,
  -- consents (the newsletter one is separate and optional)
  privacy_consent boolean not null,
  newsletter_consent boolean not null default false,
  consent_at timestamptz not null default now(),
  privacy_policy_version text not null,
  -- reserved for the future Airtable sync (not implemented yet)
  airtable_record_id text unique,
  airtable_sync_status text not null default 'PENDING',
  airtable_synced_at timestamptz,
  airtable_sync_error text,

  constraint download_registrations_request_id_key unique (request_id),
  constraint download_registrations_entry_type_check check (entry_type in ('REGISTRATION', 'EVENT')),
  constraint download_registrations_request_type_check check (request_type in ('DOWNLOAD_CSV', 'DOWNLOAD_XLSX', 'DOWNLOAD_BULK', 'MAP_CSV', 'MAP_PNG', 'MAP_PDF')),
  constraint download_registrations_file_format_check check (file_format is null or file_format in ('CSV', 'XLSX', 'PNG', 'PDF')),
  constraint download_registrations_scope_check check (download_scope is null or download_scope in ('ALL', 'FILTERED')),
  constraint download_registrations_filter_query_check check (filter_query is null or length(filter_query) <= 1000),
  constraint download_registrations_row_count_check check (row_count is null or row_count >= 0),
  constraint download_registrations_names_check check (length(btrim(first_name)) between 1 and 100 and length(btrim(last_name)) between 1 and 100),
  constraint download_registrations_email_check check (length(email) between 3 and 200 and position('@' in email) > 1),
  constraint download_registrations_locale_check check (locale in ('it', 'en')),
  constraint download_registrations_origin_check check (length(page_path) <= 200 and length(page_section) <= 60 and length(cta) <= 60),
  constraint download_registrations_privacy_consent_check check (privacy_consent = true),
  constraint download_registrations_airtable_sync_status_check check (airtable_sync_status in ('PENDING', 'SYNCED', 'ERROR'))
);

create index download_registrations_entry_idx on public.download_registrations (entry_type, created_at);
create index download_registrations_email_idx on public.download_registrations (lower(btrim(email)));

-- Security: RLS on, no policy; only the server role may write.
alter table public.download_registrations enable row level security;
revoke all on table public.download_registrations from anon, authenticated;
grant select, insert, update on table public.download_registrations to service_role;

commit;
