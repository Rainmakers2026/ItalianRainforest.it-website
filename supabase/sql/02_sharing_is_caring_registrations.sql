-- =============================================================================
-- Italian Rainforest — 02 · sharing_is_caring_registrations
-- "Sharing is caring" embed code (map / database) → POST /api/signup with reason "embed"
--   entry_type REGISTRATION = the one-time sign-up shown before the first embed code
--   entry_type EVENT        = every later copy of the embed code by a signed-up visitor
--
-- Run once in Supabase → SQL Editor (project qwdajoztlpisrzieziup).
-- Precondition (verified 2026-11-26): the table is EMPTY. The script stops if it is not.
-- =============================================================================
begin;

do $$
begin
  if exists (select 1 from public.sharing_is_caring_registrations) then
    raise exception 'sharing_is_caring_registrations is not empty: stop and plan a data migration';
  end if;
end $$;

alter table public.sharing_is_caring_registrations
  -- idempotency key generated by the browser for each action (retries do not duplicate)
  add column request_id uuid not null,
  add column entry_type text not null,
  -- for EVENT rows: request_id of the visitor's sign-up (it may live in download_registrations)
  add column registration_id uuid,
  add column embed_kind text not null,
  -- language of the embed code the visitor chose (it / en)
  add column embed_locale text,
  -- provenance: page, section, CTA, UTM (locale = real page language, already present)
  add column page_path text not null,
  add column page_section text not null,
  add column cta text not null,
  add column utm jsonb;

alter table public.sharing_is_caring_registrations
  alter column locale set not null,
  add constraint sharing_is_caring_registrations_request_id_key unique (request_id),
  add constraint sharing_is_caring_registrations_entry_type_check check (entry_type in ('REGISTRATION', 'EVENT')),
  add constraint sharing_is_caring_registrations_embed_kind_check check (embed_kind in ('MAP', 'DATABASE')),
  add constraint sharing_is_caring_registrations_embed_locale_check check (embed_locale is null or embed_locale in ('it', 'en')),
  add constraint sharing_is_caring_registrations_email_check check (length(email) between 3 and 200 and position('@' in email) > 1),
  add constraint sharing_is_caring_registrations_origin_check check (length(page_path) <= 200 and length(page_section) <= 60 and length(cta) <= 60);

create index sharing_is_caring_registrations_entry_idx on public.sharing_is_caring_registrations (entry_type, created_at);
create index sharing_is_caring_registrations_email_idx on public.sharing_is_caring_registrations (lower(btrim(email)));

-- Security: RLS on, no policy; only the server role may write.
alter table public.sharing_is_caring_registrations enable row level security;
revoke all on table public.sharing_is_caring_registrations from anon, authenticated;
grant select, insert, update on table public.sharing_is_caring_registrations to service_role;

commit;
