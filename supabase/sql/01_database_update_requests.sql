-- =============================================================================
-- Italian Rainforest — 01 · database_update_requests
-- Form "Segnala un aggiornamento / Suggest an update" → POST /api/suggest
--
-- Run once in Supabase → SQL Editor (project qwdajoztlpisrzieziup).
-- Precondition (verified 2026-11-26): the table is EMPTY, so NOT NULL columns can be
-- added without a default. The script stops if it is not.
-- Written only by the site server (service_role). RLS stays ON with no policy, so the
-- public roles (anon, authenticated) can neither read nor write personal data.
-- =============================================================================
begin;

do $$
begin
  if exists (select 1 from public.database_update_requests) then
    raise exception 'database_update_requests is not empty: stop and plan a data migration';
  end if;
end $$;

alter table public.database_update_requests
  -- idempotency key generated by the browser for each submission (retries do not duplicate)
  add column request_id uuid not null,
  add column source text not null default 'ITALIAN RAINFOREST WEBSITE',
  -- type of change proposed in the form: new player / correction / other
  add column change_type text not null,
  add column organization_name text not null,
  add column website text,
  add column details text not null,
  add column email text not null,
  -- provenance: real page language, page, section, CTA, UTM
  add column locale text not null,
  add column page_path text not null,
  add column page_section text not null,
  add column cta text not null,
  add column utm jsonb,
  -- consents (the newsletter one is separate and optional)
  add column privacy_consent boolean not null,
  add column newsletter_consent boolean not null default false,
  add column consent_at timestamptz not null default now(),
  add column privacy_policy_version text not null,
  -- moderation by the Rainmakers team (nothing is published automatically)
  add column review_status text not null default 'PENDING';

alter table public.database_update_requests
  add constraint database_update_requests_request_id_key unique (request_id),
  add constraint database_update_requests_change_type_check check (change_type in ('NEW', 'CORRECTION', 'OTHER')),
  add constraint database_update_requests_organization_check check (length(btrim(organization_name)) between 1 and 200),
  add constraint database_update_requests_website_check check (website is null or length(website) <= 300),
  add constraint database_update_requests_details_check check (length(btrim(details)) between 10 and 3000),
  add constraint database_update_requests_email_check check (length(email) between 3 and 200 and position('@' in email) > 1),
  add constraint database_update_requests_locale_check check (locale in ('it', 'en')),
  add constraint database_update_requests_origin_check check (length(page_path) <= 200 and length(page_section) <= 60 and length(cta) <= 60),
  add constraint database_update_requests_privacy_consent_check check (privacy_consent = true),
  add constraint database_update_requests_review_status_check check (review_status in ('PENDING', 'IN_REVIEW', 'APPROVED', 'REJECTED', 'PUBLISHED'));

create index database_update_requests_review_idx on public.database_update_requests (review_status, created_at);

-- Security: RLS on, no policy; only the server role may write.
alter table public.database_update_requests enable row level security;
revoke all on table public.database_update_requests from anon, authenticated;
grant select, insert on table public.database_update_requests to service_role;

commit;
